// Hash codes and bucket memberships of a set of descriptors, in flat arrays.
struct HashedDescriptions{
  // Number of descriptors.
  int nb_descriptions = 0;

  // Number of 64-bit words per hash code.
  int nb_hash_words = 0;
  // Hash codes generated by the primary hashing function: the code of
  // descriptor i is hash_codes[i * nb_hash_words, (i + 1) * nb_hash_words).
  // Bits beyond the code length are zero.
  std::vector<uint64_t> hash_codes;

  // Number of bucket groups.
  int nb_bucket_groups = 0;
  // Number of buckets in each group.
  int nb_buckets_per_group = 0;
  // bucket_ids[i * nb_bucket_groups + g] = b means that descriptor i belongs
  // to bucket b of bucket group g.
  std::vector<uint16_t> bucket_ids;

  // The buckets, in compressed sparse row form: the descriptor ids in bucket b
  // of group g are bucket_members[bucket_offsets[k], bucket_offsets[k + 1]),
  // with k = g * (nb_buckets_per_group + 1) + b, in increasing order.
  std::vector<int> bucket_offsets;
  std::vector<int> bucket_members;
  // The hash codes of the bucket members, in the same order (nb_hash_words
  // per entry), so that the codes of a bucket are read sequentially.
  std::vector<uint64_t> bucket_hash_codes;

  const uint64_t * hash_code(int i) const
  {
    return hash_codes.data() + static_cast<size_t>(i) * nb_hash_words;
  }

  const uint16_t * bucket_id(int i) const
  {
    return bucket_ids.data() + static_cast<size_t>(i) * nb_bucket_groups;
  }

  // Range [first, last) of the descriptor ids in bucket `bucket` of group `group`.
  std::pair<const int *, const int *> bucket(int group, int bucket) const
  {
    const int * offsets = bucket_offsets.data() + group * (nb_buckets_per_group + 1);
    return {bucket_members.data() + offsets[bucket],
            bucket_members.data() + offsets[bucket + 1]};
  }

  // Hash code of the bucket member at `member` (a pointer into bucket_members).
  const uint64_t * bucket_hash_code(const int * member) const
  {
    return bucket_hash_codes.data() +
      static_cast<size_t>(member - bucket_members.data()) * nb_hash_words;
  }
};

// This hasher will hash descriptors with a two-step hashing system:
// 1. it generates a hash code,
// 2. it determines which buckets the descriptors belong to.
// Retrieval step is fast since:
// - only descriptors in the same bucket are likely to be good matches.
//   - 1. a hamming distance is used for fast neighbor candidate retrieval
//   - 2. the L2 distance is computed only a reduced selection of approximate neighbor
//
// Implementation is based on the paper [1].
// If you use this matcher, please cite the paper.
class CascadeHasher {
private:

  // The number of bucket bits.
  int nb_bits_per_bucket_;
  // The number of dimensions of the Hash code.
  int nb_hash_code_;
  // The number of bucket groups.
  int nb_bucket_groups_;
  // The number of buckets in each group.
  int nb_buckets_per_group_;

public:
  CascadeHasher() = default;

  // Creates the hashing projections (cascade of two level of hash codes)
  bool Init
  (
    const uint8_t nb_hash_code = 128,
    const uint8_t nb_bucket_groups = 6,
    const uint8_t nb_bits_per_bucket = 10,
    const unsigned random_seed = std::mt19937::default_seed)
  {
    nb_bucket_groups_= nb_bucket_groups;
    nb_hash_code_ = nb_hash_code;
    nb_bits_per_bucket_ = nb_bits_per_bucket;
    nb_buckets_per_group_= 1 << nb_bits_per_bucket;

    //
    // Box Muller transform is used in the original paper to get fast random number
    // from a normal distribution with <mean = 0> and <variance = 1>.
    // Here we use C++11 normal distribution random number generator
    std::mt19937 gen(random_seed);
    std::normal_distribution<> d(0,1);

    primary_hash_projection_.resize(nb_hash_code, nb_hash_code);

    // Initialize primary hash projection.
    for (int i = 0; i < nb_hash_code; ++i)
    {
      for (int j = 0; j < nb_hash_code; ++j)
        primary_hash_projection_(i, j) = d(gen);
    }

    // Initialize secondary hash projection.
    secondary_hash_projection_.resize(nb_bucket_groups);
    for (int i = 0; i < nb_bucket_groups; ++i)
    {
      secondary_hash_projection_[i].resize(nb_bits_per_bucket_,
        nb_hash_code);
      for (int j = 0; j < nb_bits_per_bucket_; ++j)
      {
        for (int k = 0; k < nb_hash_code; ++k)
          secondary_hash_projection_[i](j, k) = d(gen);
      }
    }
    return true;
  }

  template <typename MatrixT>
  static Eigen::VectorXf GetZeroMeanDescriptor
  (
    const MatrixT & descriptions
  )
  {
    if (descriptions.rows() == 0) {
      return {};
    }
    // Compute the ZeroMean descriptor
    return descriptions.template cast<float>().colwise().mean();
  }


  template <typename MatrixT>
  HashedDescriptions CreateHashedDescriptions
  (
    const MatrixT & descriptions,
    const Eigen::VectorXf & zero_mean_descriptor
  ) const
  {
    // Steps:
    //   1) Compute hash code and hash buckets (based on the zero_mean_descriptor).
    //   2) Construct buckets.

    HashedDescriptions hashed_descriptions;
    if (descriptions.rows() == 0) {
      return hashed_descriptions;
    }

    const int nbDescriptions = static_cast<int>(descriptions.rows());
    hashed_descriptions.nb_descriptions = nbDescriptions;
    hashed_descriptions.nb_hash_words = (nb_hash_code_ + 63) / 64;
    hashed_descriptions.nb_bucket_groups = nb_bucket_groups_;
    hashed_descriptions.nb_buckets_per_group = nb_buckets_per_group_;

    // Create hash codes for each description.
    {
      hashed_descriptions.hash_codes.assign(
        static_cast<size_t>(nbDescriptions) * hashed_descriptions.nb_hash_words, 0);
      hashed_descriptions.bucket_ids.resize(
        static_cast<size_t>(nbDescriptions) * nb_bucket_groups_);
      Eigen::VectorXf descriptor(descriptions.cols());
      Eigen::VectorXf primary_projection(nb_hash_code_);
      Eigen::VectorXf secondary_projection(nb_bits_per_bucket_);
      for (int i = 0; i < nbDescriptions; ++i)
      {
        // Compute hash code.
        uint64_t * hash_code = hashed_descriptions.hash_codes.data() +
          static_cast<size_t>(i) * hashed_descriptions.nb_hash_words;
        descriptor = descriptions.row(i).template cast<float>();
        descriptor -= zero_mean_descriptor;
        primary_projection.noalias() = primary_hash_projection_ * descriptor;
        for (int j = 0; j < nb_hash_code_; ++j)
        {
          hash_code[j / 64] |= uint64_t(primary_projection(j) > 0) << (j % 64);
        }

        // Determine the bucket index for each group.
        uint16_t * bucket_ids = hashed_descriptions.bucket_ids.data() +
          static_cast<size_t>(i) * nb_bucket_groups_;
        for (int j = 0; j < nb_bucket_groups_; ++j)
        {
          uint16_t bucket_id = 0;
          secondary_projection.noalias() = secondary_hash_projection_[j] * descriptor;

          for (int k = 0; k < nb_bits_per_bucket_; ++k)
          {
            bucket_id = (bucket_id << 1) + (secondary_projection(k) > 0 ? 1 : 0);
          }
          bucket_ids[j] = bucket_id;
        }
      }
    }
    // Build the Buckets (counting sort of the descriptor ids by bucket id)
    {
      const int nb_offsets = nb_buckets_per_group_ + 1;
      hashed_descriptions.bucket_offsets.assign(
        static_cast<size_t>(nb_bucket_groups_) * nb_offsets, 0);
      hashed_descriptions.bucket_members.resize(
        static_cast<size_t>(nb_bucket_groups_) * nbDescriptions);
      for (int g = 0; g < nb_bucket_groups_; ++g)
      {
        int * offsets = hashed_descriptions.bucket_offsets.data() + g * nb_offsets;
        for (int i = 0; i < nbDescriptions; ++i)
          ++offsets[hashed_descriptions.bucket_id(i)[g] + 1];
        offsets[0] = g * nbDescriptions;
        for (int b = 0; b < nb_buckets_per_group_; ++b)
          offsets[b + 1] += offsets[b];

        // Fill the buckets, using the offsets as insertion positions, then
        // shift them back to the bucket starts.
        for (int i = 0; i < nbDescriptions; ++i)
          hashed_descriptions.bucket_members[offsets[hashed_descriptions.bucket_id(i)[g]]++] = i;
        for (int b = nb_buckets_per_group_; b > 0; --b)
          offsets[b] = offsets[b - 1];
        offsets[0] = g * nbDescriptions;
      }

      const int nb_words = hashed_descriptions.nb_hash_words;
      hashed_descriptions.bucket_hash_codes.resize(
        hashed_descriptions.bucket_members.size() * nb_words);
      for (size_t k = 0; k < hashed_descriptions.bucket_members.size(); ++k)
        std::copy_n(hashed_descriptions.hash_code(hashed_descriptions.bucket_members[k]),
          nb_words, hashed_descriptions.bucket_hash_codes.data() + k * nb_words);
    }
    return hashed_descriptions;
  }

  // Matches two collection of hashed descriptions with a fast matching scheme
  // based on the hash codes previously generated.
  template <typename MatrixT, typename DistanceType>
  void Match_HashedDescriptions
  (
    const HashedDescriptions& hashed_descriptions1,
    const MatrixT & descriptions1,
    const HashedDescriptions& hashed_descriptions2,
    const MatrixT & descriptions2,
    IndMatches * pvec_indices,
    std::vector<DistanceType> * pvec_distances,
    const int NN = 2
  ) const
  {
    // Hash codes of 128 bits (the default) get a specialized loop.
    if (hashed_descriptions1.nb_hash_words == 2)
      Match_HashedDescriptions<2>(hashed_descriptions1, descriptions1,
        hashed_descriptions2, descriptions2, pvec_indices, pvec_distances, NN);
    else
      Match_HashedDescriptions<0>(hashed_descriptions1, descriptions1,
        hashed_descriptions2, descriptions2, pvec_indices, pvec_distances, NN);
  }

  private:
  // kHashWords: number of 64-bit words of the hash codes, or 0 if given at
  // run time by the hashed descriptions.
  template <int kHashWords, typename MatrixT, typename DistanceType>
  void Match_HashedDescriptions
  (
    const HashedDescriptions& hashed_descriptions1,
    const MatrixT & descriptions1,
    const HashedDescriptions& hashed_descriptions2,
    const MatrixT & descriptions2,
    IndMatches * pvec_indices,
    std::vector<DistanceType> * pvec_distances,
    const int NN
  ) const
  {
    using MetricT = L2<typename MatrixT::Scalar>;
    MetricT metric;

    static const int kNumTopCandidates = 10;

    const int nb_hash_words =
      kHashWords > 0 ? kHashWords : hashed_descriptions1.nb_hash_words;
    // Local copies: the loop below stores to int arrays, which could alias
    // the members and force reloads.
    const int nb_hash_code = nb_hash_code_;
    const int nb_bucket_groups = nb_bucket_groups_;

    // Distinct candidates of the current query, in order of first appearance:
    // descriptor ids and hamming distances.
    std::vector<int> candidate_ids;
    std::vector<int> candidate_hamming_distances;

    // Number of the current query's candidates with each hamming distance.
    std::vector<int> num_descriptors_with_hamming_distance(nb_hash_code + 1, 0);

    // last_query[id] == i means that descriptor id of the database is already
    // a candidate of query i (prevents duplicates).
    std::vector<int> last_query(hashed_descriptions2.nb_descriptions, -1);

    // Preallocate the container for keeping euclidean distances.
    std::vector<std::pair<DistanceType, int>> candidate_euclidean_distances;
    candidate_euclidean_distances.reserve(kNumTopCandidates);

    for (int i = 0; i < hashed_descriptions1.nb_descriptions; ++i)
    {
      candidate_ids.clear();
      candidate_hamming_distances.clear();
      candidate_euclidean_distances.clear();

      const uint64_t * hash_code = hashed_descriptions1.hash_code(i);
      const uint16_t * bucket_ids = hashed_descriptions1.bucket_id(i);

      // Accumulate all descriptors in each bucket group that are in the same
      // bucket id as the query descriptor, and compute the hamming distance of
      // each distinct one based on the hash code.
      size_t nb_candidates = 0;
      for (int j = 0; j < nb_bucket_groups; ++j)
      {
        const auto bucket = hashed_descriptions2.bucket(j, bucket_ids[j]);
        nb_candidates += bucket.second - bucket.first;
        const uint64_t * candidate_hash_code =
          hashed_descriptions2.bucket_hash_code(bucket.first);
        for (const int * it = bucket.first; it != bucket.second;
          ++it, candidate_hash_code += nb_hash_words)
        {
          const int candidate_id = *it;
          if (last_query[candidate_id] == i)
            continue;
          last_query[candidate_id] = i;
          const int hamming_distance = HammingDistance(
            hash_code, candidate_hash_code, nb_hash_words);
          ++num_descriptors_with_hamming_distance[hamming_distance];
          candidate_ids.push_back(candidate_id);
          candidate_hamming_distances.push_back(hamming_distance);
        }
      }

      // Find the hamming distance threshold of the k best candidates: all
      // candidates closer than it, and the first num_at_threshold found at it.
      int threshold = 0;
      int num_at_threshold = kNumTopCandidates;
      while (threshold < nb_hash_code &&
        num_descriptors_with_hamming_distance[threshold] < num_at_threshold)
      {
        num_at_threshold -= num_descriptors_with_hamming_distance[threshold];
        ++threshold;
      }
      for (const int hamming_distance : candidate_hamming_distances)
        num_descriptors_with_hamming_distance[hamming_distance] = 0;

      // Skip matching this descriptor if there are not at least NN candidates.
      if (nb_candidates <= static_cast<size_t>(NN))
      {
        continue;
      }

      // Compute the euclidean distance of the k descriptors with the best
      // hamming distance.
      for (size_t k = 0; k < candidate_ids.size(); ++k)
      {
        const int hamming_distance = candidate_hamming_distances[k];
        if (hamming_distance > threshold ||
          (hamming_distance == threshold && num_at_threshold-- <= 0))
          continue;
        const int candidate_id = candidate_ids[k];
        const DistanceType distance = metric(
          descriptions2.row(candidate_id).data(),
          descriptions1.row(i).data(),
          descriptions1.cols());

        candidate_euclidean_distances.emplace_back(distance, candidate_id);
      }

      // Assert that each query is having at least NN retrieved neighbors
      if (candidate_euclidean_distances.size() >= NN)
      {
        // Find the top NN candidates based on euclidean distance.
        std::partial_sort(candidate_euclidean_distances.begin(),
          candidate_euclidean_distances.begin() + NN,
          candidate_euclidean_distances.end());
        // save resulting neighbors
        for (int l = 0; l < NN; ++l)
        {
          pvec_distances->emplace_back(candidate_euclidean_distances[l].first);
          pvec_indices->emplace_back(IndMatch(i,candidate_euclidean_distances[l].second));
        }
      }
      //else -> too few candidates... (save no one)
    }
  }

  static int HammingDistance
  (
    const uint64_t * a,
    const uint64_t * b,
    int nb_words
  )
  {
    int distance = 0;
    for (int k = 0; k < nb_words; ++k)
      distance += static_cast<int>(std::bitset<64>(a[k] ^ b[k]).count());
    return distance;
  }

  // Primary hashing function.
  Eigen::MatrixXf primary_hash_projection_;

  // Secondary hashing function.
  std::vector<Eigen::MatrixXf> secondary_hash_projection_;
};

